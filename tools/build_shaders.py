"""Compile the runtime's own GLSL shaders (runtime/shaders/*.comp, *.vert, *.frag) into C headers of SPIR-V words.

    python -I tools/build_shaders.py [--check] [--glslang PATH]

Each runtime/shaders/<name>.<stage> becomes runtime/gfx/<name>_spv.h, which declares `static const uint32_t
<name>_spv[]` and records the SHA-256 of the source it came from. The headers are committed, so building mlb.exe needs
no shader compiler. Run this after editing a shader; --check only reports headers that no longer match their source.
Needs glslang (https://github.com/KhronosGroup/glslang/releases): --glslang, the GLSLANG environment variable,
~/tools/glslang-*/bin/glslang.exe or glslang on PATH. After TotK Recomp tools/build_shaders.py @ ae30a61 (MIT), which
uses glslc.
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'runtime' / 'shaders'
OUT = ROOT / 'runtime' / 'gfx'
STAGES = {'.comp', '.vert', '.frag'}


def source_hash(src):
    return hashlib.sha256(src.read_bytes().replace(b'\r\n', b'\n')).hexdigest()   # the same on a CRLF checkout


def header_path(src):
    return OUT / f'{src.stem}_spv.h'


def header_of(src, words):
    lines = [f'// Generated by tools/build_shaders.py from runtime/shaders/{src.name}; do not edit.',
             f'// source sha256 {source_hash(src)}',
             '#pragma once',
             '#include <stdint.h>',
             f'static const uint32_t {src.stem}_spv[] = {{']
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def find_glslang(arg):
    if arg:
        return arg
    if os.environ.get('GLSLANG'):
        return os.environ['GLSLANG']
    found = sorted(Path.home().glob('tools/glslang-*/bin/glslang.exe'))
    if found:
        return str(found[-1])
    return shutil.which('glslang') or shutil.which('glslangValidator')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--glslang')
    a = ap.parse_args()
    srcs = sorted(p for p in SRC.iterdir() if p.suffix in STAGES)
    stale = [s for s in srcs if not header_path(s).exists()
             or f'// source sha256 {source_hash(s)}' not in header_path(s).read_text(encoding='utf-8')]
    if a.check:
        for s in stale:
            print(f'stale: {header_path(s).relative_to(ROOT)} (from {s.relative_to(ROOT)})')
        return 1 if stale else 0
    glslang = find_glslang(a.glslang)
    if not glslang:
        raise SystemExit('glslang not found: pass --glslang or set GLSLANG')
    for s in srcs:
        with tempfile.TemporaryDirectory() as td:
            spv = Path(td) / 'out.spv'
            r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.1', '-Os', '-o', str(spv), str(s)],
                               capture_output=True, text=True)
            if r.returncode:
                sys.stderr.write(r.stdout + r.stderr)
                raise SystemExit(f'{s.name}: compile failed')
            data = spv.read_bytes()
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        h = header_path(s)
        text = header_of(s, words)
        if not h.exists() or h.read_text(encoding='utf-8') != text:
            h.write_text(text, encoding='utf-8', newline='\n')
            print(f'{h.relative_to(ROOT)}: {len(words)} words')
    return 0


if __name__ == '__main__':
    sys.exit(main())
